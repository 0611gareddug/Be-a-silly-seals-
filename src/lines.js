export function line(key, vars = {}) {
  const arr = LINES[key];
  if (!arr) return '';
  let s = arr[Math.floor(Math.random() * arr.length)];
  for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v));
  return s;
}
